BEGIN;

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS vector;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- -----------------------------------------------------------------------------
-- Seguridad y autenticación
-- -----------------------------------------------------------------------------

CREATE TABLE roles (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT roles_code_format CHECK (code ~ '^[a-z][a-z0-9_]*$')
);

CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    role_id SMALLINT NOT NULL REFERENCES roles(id),
    email CITEXT NOT NULL UNIQUE,
    display_name VARCHAR(120) NOT NULL,
    password_hash TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    monthly_token_limit INTEGER NOT NULL DEFAULT 100000,
    monthly_tokens_used INTEGER NOT NULL DEFAULT 0,
    token_period_start DATE NOT NULL DEFAULT date_trunc('month', CURRENT_DATE)::date,
    failed_login_attempts SMALLINT NOT NULL DEFAULT 0,
    locked_until TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT users_email_format CHECK (
        email::text ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
    ),
    CONSTRAINT users_display_name_not_blank CHECK (btrim(display_name) <> ''),
    CONSTRAINT users_password_hash_not_blank CHECK (btrim(password_hash) <> ''),
    CONSTRAINT users_monthly_token_limit_nonnegative CHECK (monthly_token_limit >= 0),
    CONSTRAINT users_monthly_tokens_used_nonnegative CHECK (monthly_tokens_used >= 0)
);

CREATE INDEX idx_users_role_id ON users(role_id);
CREATE INDEX idx_users_active ON users(is_active) WHERE is_active = TRUE;

CREATE TRIGGER trg_users_set_updated_at
BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Cada refresh token se guarda como hash. El token original nunca se persiste.
CREATE TABLE user_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    refresh_token_hash CHAR(64) NOT NULL UNIQUE,
    user_agent TEXT,
    ip_address INET,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT sessions_expiration_after_creation CHECK (expires_at > created_at),
    CONSTRAINT sessions_refresh_hash_format CHECK (refresh_token_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX idx_user_sessions_user_id ON user_sessions(user_id);
CREATE INDEX idx_user_sessions_active
    ON user_sessions(user_id, expires_at)
    WHERE revoked_at IS NULL;

-- -----------------------------------------------------------------------------
-- Catálogo bibliográfico
-- -----------------------------------------------------------------------------

CREATE TABLE publishers (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name VARCHAR(180) NOT NULL,
    country_code CHAR(2),
    website_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT publishers_name_unique UNIQUE (name),
    CONSTRAINT publishers_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT publishers_country_code_format CHECK (
        country_code IS NULL OR country_code ~ '^[A-Z]{2}$'
    )
);

CREATE TRIGGER trg_publishers_set_updated_at
BEFORE UPDATE ON publishers
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE authors (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name VARCHAR(180) NOT NULL,
    biography TEXT,
    birth_date DATE,
    death_date DATE,
    country_code CHAR(2),
    external_source VARCHAR(50),
    external_id VARCHAR(150),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT authors_full_name_not_blank CHECK (btrim(full_name) <> ''),
    CONSTRAINT authors_life_dates_valid CHECK (
        death_date IS NULL OR birth_date IS NULL OR death_date >= birth_date
    ),
    CONSTRAINT authors_country_code_format CHECK (
        country_code IS NULL OR country_code ~ '^[A-Z]{2}$'
    ),
    CONSTRAINT authors_external_identity_unique UNIQUE (external_source, external_id)
);

CREATE INDEX idx_authors_full_name ON authors(full_name);

CREATE TRIGGER trg_authors_set_updated_at
BEFORE UPDATE ON authors
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE genres (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id SMALLINT REFERENCES genres(id) ON DELETE SET NULL,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT genres_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT genres_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

CREATE TABLE books (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    publisher_id UUID REFERENCES publishers(id) ON DELETE SET NULL,
    isbn_10 VARCHAR(10) UNIQUE,
    isbn_13 VARCHAR(13) UNIQUE,
    title VARCHAR(250) NOT NULL,
    subtitle VARCHAR(250),
    synopsis TEXT,
    publication_year SMALLINT,
    language_code VARCHAR(10) NOT NULL DEFAULT 'es',
    page_count INTEGER,
    cover_url TEXT,
    source_url TEXT,
    external_source VARCHAR(50),
    external_id VARCHAR(150),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    search_vector TSVECTOR GENERATED ALWAYS AS (
        to_tsvector(
            'simple',
            coalesce(title, '') || ' ' ||
            coalesce(subtitle, '') || ' ' ||
            coalesce(synopsis, '')
        )
    ) STORED,
    CONSTRAINT books_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT books_isbn_10_format CHECK (isbn_10 IS NULL OR isbn_10 ~ '^[0-9]{9}[0-9X]$'),
    CONSTRAINT books_isbn_13_format CHECK (isbn_13 IS NULL OR isbn_13 ~ '^[0-9]{13}$'),
    CONSTRAINT books_publication_year_valid CHECK (
        publication_year IS NULL OR publication_year BETWEEN 1000 AND 2100
    ),
    CONSTRAINT books_page_count_positive CHECK (page_count IS NULL OR page_count > 0),
    CONSTRAINT books_external_identity_unique UNIQUE (external_source, external_id)
);

CREATE INDEX idx_books_publisher_id ON books(publisher_id);
CREATE INDEX idx_books_title ON books(title);
CREATE INDEX idx_books_publication_year ON books(publication_year);
CREATE INDEX idx_books_active ON books(is_active) WHERE is_active = TRUE;
CREATE INDEX idx_books_search_vector ON books USING GIN(search_vector);

CREATE TRIGGER trg_books_set_updated_at
BEFORE UPDATE ON books
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE book_authors (
    book_id UUID NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    author_id UUID NOT NULL REFERENCES authors(id) ON DELETE RESTRICT,
    author_order SMALLINT NOT NULL DEFAULT 1,
    contribution VARCHAR(40) NOT NULL DEFAULT 'author',
    PRIMARY KEY (book_id, author_id, contribution),
    CONSTRAINT book_authors_order_positive CHECK (author_order > 0),
    CONSTRAINT book_authors_contribution_allowed CHECK (
        contribution IN ('author', 'editor', 'translator', 'illustrator')
    )
);

CREATE INDEX idx_book_authors_author_id ON book_authors(author_id);

CREATE TABLE book_genres (
    book_id UUID NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    genre_id SMALLINT NOT NULL REFERENCES genres(id) ON DELETE RESTRICT,
    PRIMARY KEY (book_id, genre_id)
);

CREATE INDEX idx_book_genres_genre_id ON book_genres(genre_id);

-- Vista tabular útil para el catálogo, la API y la importación inicial en Power BI.
CREATE VIEW book_catalog AS
SELECT
    b.id,
    b.isbn_10,
    b.isbn_13,
    b.title,
    b.subtitle,
    b.synopsis,
    b.publication_year,
    b.language_code,
    b.page_count,
    b.cover_url,
    b.is_active,
    p.name AS publisher,
    coalesce(a.authors, '[]'::jsonb) AS authors,
    coalesce(g.genres, '[]'::jsonb) AS genres,
    b.created_at,
    b.updated_at
FROM books b
LEFT JOIN publishers p ON p.id = b.publisher_id
LEFT JOIN LATERAL (
    SELECT jsonb_agg(
        jsonb_build_object(
            'id', au.id,
            'name', au.full_name,
            'contribution', ba.contribution
        )
        ORDER BY ba.author_order
    ) AS authors
    FROM book_authors ba
    JOIN authors au ON au.id = ba.author_id
    WHERE ba.book_id = b.id
) a ON TRUE
LEFT JOIN LATERAL (
    SELECT jsonb_agg(
        jsonb_build_object('id', ge.id, 'name', ge.name)
        ORDER BY ge.name
    ) AS genres
    FROM book_genres bg
    JOIN genres ge ON ge.id = bg.genre_id
    WHERE bg.book_id = b.id
) g ON TRUE;

COMMIT;
